-- =====================================================================
-- ShoppingList — Categorias de artigos (como no FestasBV).
-- IDEMPOTENTE e sem DROP/DELETE/REVOKE. Correr depois do schema.sql.
-- Já aplicado (migração shoppinglist_categorias).
--
--   categorias         o dicionário ("Talho", "Legumes", …). Gerido pelo
--                      admin nas Definições.
--   artigo_categorias  a memória artigo→categoria. Chave = nome normalizado
--                      (minúsculas, sem acentos — artKey() na app), por isso
--                      "Pão" e "pao" são o mesmo artigo. É partilhada por
--                      todas as listas: classifica-se uma vez, fica sabido.
--
-- As duas tabelas nascem com uma CÓPIA do que existe em festasbv (dicionário
-- e memória), mais umas categorias e artigos típicos de casa. A partir daí
-- cada app segue o seu caminho — é cópia, não ligação, porque quem usa esta
-- app pode não ter acesso às Festas.
-- =====================================================================

create table if not exists shoppinglist.categorias (
  id         bigint generated by default as identity primary key,
  nome       text not null unique check (char_length(nome) between 1 and 40),
  descritivo text not null default '',
  criado_em  timestamptz not null default now()
);

create table if not exists shoppinglist.artigo_categorias (
  artigo_key    text primary key check (char_length(artigo_key) between 1 and 120),
  categoria_id  bigint not null references shoppinglist.categorias(id) on delete cascade,
  origem        text not null default 'manual',   -- 'manual' | 'ai' (vindo das Festas) | 'base'
  atualizado_em timestamptz not null default now()
);

alter table shoppinglist.categorias        enable row level security;
alter table shoppinglist.artigo_categorias enable row level security;

do $pol$
begin
  if exists (select 1 from pg_policies where schemaname = 'shoppinglist' and tablename = 'categorias') then
    raise notice 'policies das categorias já existem — nada a fazer';
    return;
  end if;
  -- dicionário: todos leem, só o admin gere
  create policy ct_select on shoppinglist.categorias for select to authenticated
    using (shoppinglist.is_allowed());
  create policy ct_insert on shoppinglist.categorias for insert to authenticated
    with check (shoppinglist.is_admin());
  create policy ct_update on shoppinglist.categorias for update to authenticated
    using (shoppinglist.is_admin()) with check (shoppinglist.is_admin());
  create policy ct_delete on shoppinglist.categorias for delete to authenticated
    using (shoppinglist.is_admin());
  -- memória: a casa é partilhada, qualquer pessoa com acesso classifica e corrige
  create policy ac_select on shoppinglist.artigo_categorias for select to authenticated
    using (shoppinglist.is_allowed());
  create policy ac_insert on shoppinglist.artigo_categorias for insert to authenticated
    with check (shoppinglist.is_allowed());
  create policy ac_update on shoppinglist.artigo_categorias for update to authenticated
    using (shoppinglist.is_allowed()) with check (shoppinglist.is_allowed());
  create policy ac_delete on shoppinglist.artigo_categorias for delete to authenticated
    using (shoppinglist.is_allowed());
end $pol$;

grant select, insert, update, delete on shoppinglist.categorias, shoppinglist.artigo_categorias to authenticated;
grant all on shoppinglist.categorias, shoppinglist.artigo_categorias to service_role;

-- ── Dicionário: o das Festas + categorias de casa ────────────────────
insert into shoppinglist.categorias (nome, descritivo)
  select nome, descritivo from festasbv.categorias
  on conflict (nome) do nothing;


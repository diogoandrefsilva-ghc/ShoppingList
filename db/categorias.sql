-- ── Memória: a das Festas (pelo NOME da categoria, os ids são outros) ──
insert into shoppinglist.artigo_categorias (artigo_key, categoria_id, origem)
  select ac.artigo_key, sc.id, ac.origem
    from festasbv.artigo_categorias ac
    join festasbv.categorias fc on fc.id = ac.categoria_id
    join shoppinglist.categorias sc on sc.nome = fc.nome
   where char_length(ac.artigo_key) between 1 and 120
  on conflict (artigo_key) do nothing;

